def load_page(source, archive, scan):
    name = f"K57-11_57_scan{scan:03}.jpg"
    stream = BytesIO(archive.read(name)) if archive else source / name
    with Image.open(stream) as page:
        image = page.convert("L")
    if scan in (90, 95):
        image = image.transpose(Image.Transpose.ROTATE_180)
        # Match the grayscale upright working copy used for the two English leaves.
        upright = BytesIO()
        image.save(upright, "JPEG", qtables=[UPRIGHT_QUANTIZATION])
        upright.seek(0)
        with Image.open(upright) as page:
            image = page.copy()
    return image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="the attached ZIP or its extracted image directory")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parent.parent / "crops")
    parser.add_argument("--blind", action="store_true", help="also recreate the original blind-reading windows")
    arguments = parser.parse_args()
    selections = CROPS + BLIND_WINDOWS if arguments.blind else CROPS
    arguments.output.mkdir(parents=True, exist_ok=True)
    archive = ZipFile(arguments.source) if arguments.source.is_file() else None
    page = None
    previous_scan = None
    try:
        for name, scan, source_box, angle, zoom_box in selections:
            if scan != previous_scan:
                page = load_page(arguments.source, archive, scan)
                previous_scan = scan
            detail = ImageEnhance.Contrast(page.crop(source_box)).enhance(1.45)
            detail = detail.resize((3 * detail.width, 3 * detail.height), Image.Resampling.LANCZOS)
            if angle:
                detail = detail.rotate(angle, expand=True, resample=Image.Resampling.BICUBIC,
                                       fillcolor="white")
            detail.crop(zoom_box).save(arguments.output / name, compress_level=2)
    finally:
        if archive:
            archive.close()
    print(f"Recreated {len(selections)} crops in {arguments.output}")


if __name__ == "__main__":
    main()
