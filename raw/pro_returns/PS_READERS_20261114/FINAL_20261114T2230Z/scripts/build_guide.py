"""Build the standalone guide only from paragraphs written after section reviews."""
from pathlib import Path
import re,json,hashlib
from build_readers import group
P=Path(__file__).resolve().parents[1]
base=(P/'scripts/reader_preamble.tex').read_text()
preamble=base.split(r'\newcommand{\psfrontmatter}')[0]
preamble+=r'\hyphenation{Gro-then-dieck abel-ian-iza-tion}'+'\n'
credit=base.split(r'\chapter*{Editorial statement}',1)[1].split(r'\section*{How to read this form}',1)[0]
checked=len(list((P/'checked_pages').glob('*.tex')))
chunks=[];sections=[]
def section_order(path):
    root_order={'134_2_frontmatter.tex':0,'134_2_letter_overview.tex':1,'134_2_letter.tex':2,'134_2_appendix.tex':3,'134_2_notes.tex':4}
    if path.name in root_order:return (0,root_order[path.name],path.name)
    if 'brown' in path.name.lower():return (2,0,path.name)
    return (1,0,path.name)
for p in sorted((P/'guide_sections').glob('*.tex'),key=section_order):
    s=re.sub(r'(?m)^\s*%[^\n]*(?:\n|$)','',p.read_text())
    positions=[]
    for m in re.finditer(r'\\(?:subsection|section|paragraph)\*?\{',s):
        title,end=group(s,m.end()-1);positions.append((m.start(),end,title))
    if not positions and s.strip():raise ValueError(('guide fragment lacks heading',p.name))
    for i,(start,end,title) in enumerate(positions):
        stop=positions[i+1][0] if i+1<len(positions) else len(s)
        body=re.sub(r'\n\s*\n+',' ',s[end:stop].strip())
        if not body:raise ValueError(('empty section paragraph',p.name,title))
        chunks.append(r'\subsection*{'+title+'}\n'+body+'\n\n')
        sections.append({'fragment':'guide_sections/'+p.name,'heading':title,'paragraph_sha256':hashlib.sha256(body.encode()).hexdigest()})
numbered=[]
for item in sections:
    title=item['heading']
    match=re.match(r'\s*(?:\\S\s*)?(\d+)(.*)',title)
    if match:
        n=int(match[1]);tail=match[2]
        if n==16 and re.match(r"\s*(?:\$?['′]|\$?\^\{?\\prime)",tail):numbered.append("16prime")
        elif 1<=n<=140:numbered.append(str(n))
expected=[str(n) for n in range(1,17)]+['16prime']+[str(n) for n in range(17,141)]
complete=checked==706 and numbered==expected
status='Complete guide to the checked typescript and appendix' if complete else f'WORKING GUIDE: {len(sections)} completed section/front-matter paragraphs; {checked} of 706 source pages reviewed'
top=r'''% Generated by scripts/build_guide.py from reviewed-section paragraphs.
\def\EditionMode{3}
\def\EditionLabel{A guide for the reader}
'''+r'\def\EditionStatus{'+status+'}\n'
front=r'''
\begin{document}
\hypersetup{pageanchor=false}
\begin{titlepage}\raggedright
{\Large Alexander Grothendieck\par}\vspace{12mm}
{\Huge Pursuing Stacks\par}\medskip{\LARGE 1983\par}\vspace{12mm}
{\Large A guide for the reader\par}\vspace{8mm}
{\large\EditionStatus\par}\vfill
Université de Montpellier, Grothendieck archive, cotes 134-2--134-8.\par
Including the appendix translation by R. Brown, cote 134-2, sites 115--143.\par
\vspace*{2mm}\end{titlepage}\hypersetup{pageanchor=true}
\chapter*{Editorial statement}
'''+credit+r'''
\section*{Using this guide}
Each paragraph describes a section already checked against both supplied scan halves. It identifies the section's task, terminology, dependencies, revisions and consequential witness differences. Mathematical cautions are editorial observations, distinguished from the author's statements; they do not alter the readers. Archive sites and internal typescript folios are kept distinct, especially where the initial letter has been reordered or renumbered. The account is provisional wherever the relevant later section has not yet been reviewed.

The guide is incomplete while source collation continues. No paragraph for an unreviewed section has been supplied from the arXiv witness alone. The completed paragraphs follow the original section order; gaps in the current working guide are intentional and will close as their sections are checked.
\chapter*{Section guide}
'''
references=r'''
\chapter*{Sources}
Grothendieck, A. (1983). \emph{Pursuing Stacks} [Typescript with handwritten revisions; cotes 134-2--134-8]. Grothendieck archive, Université de Montpellier. The supplied page images and their metadata are the primary witnesses for this edition.

Grothendieck, A. (2021). \emph{Pursuing Stacks} (M. Carmona, with the collaboration of U. Buchholtz, Eds.; arXiv:2111.01000, version 2). Extended from the 2015 edition by ``the scrivener''; CC0 1.0. This edition is consulted as a comparison witness, not reproduced as the source of record.

Brown, R. (Trans.). (n.d.). \emph{English translation of the mathematical part of two letters from Alexander Grothendieck to L. Breen, 1975} [Typescript; prepared with assistance from L. Breen and J-L. Loday]. Grothendieck archive, Université de Montpellier, cote 134-2, sites 115--143.
\end{document}
'''
if complete:
    front=front.replace('The account is provisional wherever the relevant later section has not yet been reviewed.','All 706 source pages have completed their recorded image review. Statements that remain conjectural or provisional in the typescript are identified as such.')
    front=front.replace('The guide is incomplete while source collation continues. No paragraph for an unreviewed section has been supplied from the arXiv witness alone. The completed paragraphs follow the original section order; gaps in the current working guide are intentional and will close as their sections are checked.','The section paragraphs follow the original order, including the separately numbered section~16-prime. Additional paragraphs cover the front matter, the complete letter to Quillen, the associated letters and notes, and Brown\'s translation. The supplied scans govern the account; the arXiv edition is a comparison witness.')
(P/'readers/PS_GUIDE.tex').write_text(top+preamble+front+''.join(chunks)+references)
(P/'records/GUIDE_MANIFEST.json').write_text(json.dumps({'complete':complete,'reviewed_pages':checked,'numbered_sections':numbered,'numbered_sections_in_complete_source_order':numbered==expected,'missing_numbered_sections':[n for n in expected if n not in numbered],'paragraphs':sections},indent=2)+'\n')
print(json.dumps({'guide_paragraphs':len(sections),'reviewed_pages':checked,'complete':complete,'missing_numbered_sections':[n for n in expected if n not in numbered]}))
