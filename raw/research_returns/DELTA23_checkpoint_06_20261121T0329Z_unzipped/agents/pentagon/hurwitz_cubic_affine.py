#!/usr/bin/env python3
"""Exact finite Hurwitz orbit in F9^2 : H48, with a noncentral product.

No conclusion is drawn when the stated orbit bound is reached.  Closed orbits
give literal B4/Z actions; all relations are checked before a certificate is
written.  Pair-group analysis is a separate, optional operation.
"""
import argparse, collections, json, pathlib, time
import numpy as np

ROOT=pathlib.Path(__file__).parent
def build():
 add=np.array([[((x%3+y%3)%3)+3*((x//3+y//3)%3) for y in range(9)] for x in range(9)],dtype=np.int16)
 neg=np.array([(-(x%3)%3)+3*((-(x//3))%3) for x in range(9)],dtype=np.int16)
 mul=np.array([[((x%3*(y%3)-x//3*(y//3))%3)+3*((x%3*(y//3)+x//3*(y%3))%3) for y in range(9)] for x in range(9)],dtype=np.int16)
 def mm2(a,b):
  return tuple(int(v) for v in (add[mul[a[0],b[0]],mul[a[1],b[2]]],add[mul[a[0],b[1]],mul[a[1],b[3]]],add[mul[a[2],b[0]],mul[a[3],b[2]]],add[mul[a[2],b[1]],mul[a[3],b[3]]]))
 identity=(1,0,0,1);sm=(0,3,6,0);rm=(0,2,1,2)
 H=[identity];hi={identity:0}
 for h in H:
  for g in (sm,rm):
   v=mm2(h,g)
   if v not in hi:hi[v]=len(H);H.append(v)
 assert len(H)==48
 hm=np.array([[hi[mm2(a,b)] for b in H] for a in H],dtype=np.int16)
 hinv=np.array([next(j for j in range(48) if hm[i,j]==0) for i in range(48)],dtype=np.int16)
 V=np.array([(a,b) for a in range(9) for b in range(9)],dtype=np.int16)
 va=(add[V[:,None,0],V[None,:,0]]*9+add[V[:,None,1],V[None,:,1]]).astype(np.int16)
 vn=(neg[V[:,0]]*9+neg[V[:,1]]).astype(np.int16)
 act=np.array([add[mul[a,V[:,0]],mul[b,V[:,1]]]*9+add[mul[c,V[:,0]],mul[d,V[:,1]]] for a,b,c,d in H],dtype=np.int16)
 def mm(a,b):
  a=np.asarray(a,dtype=np.int64);b=np.asarray(b,dtype=np.int64)
  v,h=a//48,a%48;w,k=b//48,b%48
  return va[v,act[h,w]].astype(np.int64)*48+hm[h,k]
 allg=np.arange(3888,dtype=np.int64)
 inv=act[hinv[allg%48],vn[allg//48]].astype(np.int64)*48+hinv[allg%48]
 assert np.all(mm(allg,inv)==0)
 s=hi[sm];r=9*48+hi[rm]
 assert mm(s,s)==0 and mm(mm(r,r),r)==0
 # Group generated by s,r is E, not a guessed abstract isomorphism.
 seen={0};todo=[0]
 for a in todo:
  for g in (s,r):
   b=int(mm(a,g))
   if b not in seen:seen.add(b);todo.append(b)
 assert len(seen)==3888
 return mm,inv,s,r,H

def run(seed='ssrr',limit=100000):
 st=time.monotonic();mm,iv,s,r,H=build();n=3888;allg=np.arange(n,dtype=np.int64)
 if seed=='ssrr':initial=(s,s,r,r)
 elif seed=='srsr':initial=(s,r,s,r)
 elif seed.startswith('ssss'):
  # Conjugate involutions retaining a nontrivial fixed product.
  rs=int(mm(mm(r,s),iv[r]));r2=int(mm(r,r));rrs=int(mm(mm(r2,s),iv[r2]))
  choices={'ssss0':(s,rs,s,rs),'ssss1':(s,rs,rrs,s),'ssss2':(s,rs,rrs,rs)}
  initial=choices[seed]
 else:raise ValueError(seed)
 p=int(mm(mm(mm(initial[0],initial[1]),initial[2]),initial[3]))
 assert p!=0, 'Product1 is a forgetful family and is excluded here.'
 cent=allg[mm(allg,p)==mm(p,allg)]
 conj=mm(mm(cent[:,None],allg[None,:]),iv[cent[:,None]])
 def canon(t):
  a=conj[:,np.asarray(t,dtype=int)[:3]]
  code=a[:,0]*n*n+a[:,1]*n+a[:,2]
  j=int(np.argmin(code));v=tuple(int(x) for x in a[j]);d=int(mm(iv[int(mm(mm(v[0],v[1]),v[2]))],p))
  return v+(d,)
 start=canon(initial);reps=[start];idx={start:0};edges=[]
 for row in reps:
  ee=[]
  for j in range(3):
   t=list(row);a,b=t[j:j+2];t[j]=int(mm(mm(a,b),iv[a]));t[j+1]=a;t=canon(t)
   k=idx.get(t)
   if k is None:
    k=len(reps);idx[t]=k;reps.append(t)
    if len(reps)>limit:
     out={'group_order':3888,'seed':seed,'product':p,'product_centralizer_order':len(cent),'orbit_lower_bound':len(reps),'status':'BOUND_REACHED_NO_CONCLUSION','elapsed_seconds':time.monotonic()-st}
     ROOT.joinpath(f'hurwitz_cubic_{seed}.json').write_text(json.dumps(out,indent=2)+'\n');print(json.dumps(out),flush=True);return
   ee.append(k)
  edges.append(ee)
  if len(edges)%10000==0:print(f'{seed}: processed {len(edges)}, found {len(reps)}',flush=True)
 ps=np.array(edges,dtype=np.int64).T;N=len(reps);I=np.arange(N)
 co=lambda a,b:a[b]
 assert all(len(set(v))==N for v in ps)
 assert np.array_equal(co(co(ps[0],ps[1]),ps[0]),co(co(ps[1],ps[0]),ps[1]))
 assert np.array_equal(co(co(ps[1],ps[2]),ps[1]),co(co(ps[2],ps[1]),ps[2]))
 assert np.array_equal(co(ps[0],ps[2]),co(ps[2],ps[0]))
 z=co(co(ps[0],ps[1]),ps[2]);z=co(co(co(z,z),z),z);assert np.array_equal(z,I)
 np.savez_compressed(ROOT/f'hurwitz_cubic_{seed}.npz',generators=ps,representatives=np.array(reps),initial=np.array(initial),product=p)
 out={'group_order':3888,'seed':seed,'product':p,'product_centralizer_order':len(cent),'orbit_degree':N,'status':'CLOSED_BRAID_AND_FULL_TWIST_PASS','elapsed_seconds':time.monotonic()-st}
 ROOT.joinpath(f'hurwitz_cubic_{seed}.json').write_text(json.dumps(out,indent=2)+'\n');print(json.dumps(out),flush=True)

if __name__=='__main__':
 ap=argparse.ArgumentParser();ap.add_argument('--seed',default='ssrr');ap.add_argument('--limit',type=int,default=100000);args=ap.parse_args();run(args.seed,args.limit)
