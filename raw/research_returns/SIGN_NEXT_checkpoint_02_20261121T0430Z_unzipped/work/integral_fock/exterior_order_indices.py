#!/usr/bin/env python3
"""Exact image-order indices in the actual symplectic exterior lattice.
Compressed by identical singleton blocks; no integral primitive splitting.
Each v=0,...,n is the actual Boolean block with v empty/full pairs.
Z[L,D] and its degree-projector/divided-power variants are generated by
right-multiplication/Hermite closure. Smith of the embedded lattice measures
index in the canonical saturation in End_Z of the actual exterior lattice.
"""
from pathlib import Path
import json, math, time
import sympy as S
from sympy.matrices.normalforms import hermite_normal_form, smith_normal_form
from sympy.polys.domains import ZZ
ROOT=Path(__file__).resolve().parent

def models(n):
    sizes=[2**v for v in range(n+1)]
    starts=[0]
    for sz in sizes: starts.append(starts[-1]+sz*sz)
    N=starts[-1]
    Es=[];Fs=[];Ps=[[] for _ in range(2*n+1)]
    for v,sz in enumerate(sizes):
        E=S.zeros(sz);F=S.zeros(sz)
        for a in range(sz):
            for b in range(v):
                if not (a>>b)&1:
                    E[a|(1<<b),a]=1
            deg=n-v+2*a.bit_count()
            for j in range(2*n+1):
                pass
        F=E.T
        Es.append(E);Fs.append(F)
        for j in range(2*n+1):
            Ps[j].append(S.diag(*[int(n-v+2*a.bit_count()==j) for a in range(sz)]))
    def vec(mats):
        return S.Matrix([entry for M in mats for entry in M])
    def mul_right(B, gs):
        ans=S.zeros(N,B.cols)
        for k,(sz,g) in enumerate(zip(sizes,gs)):
            start=starts[k]
            # Row-major vec(A*g) = (I tensor g^T)*vec(A).
            for a in range(sz):
                for b in range(sz):
                    target=start+a*sz+b
                    for c in range(sz):
                        val=g[c,b]
                        if val:
                            source=start+a*sz+c
                            ans[target,:]+=val*B[source,:]
        return ans
    return sizes,vec,mul_right,Es,Fs,Ps

def one(n,kind):
    sizes,vec,mul,E,F,P=models(n)
    gens=[E,F]
    if 'pi' in kind: gens+=P
    if 'div' in kind:
        for k in range(2,n+1):
            gens.append([G**k/math.factorial(k) for G in E])
            gens.append([G**k/math.factorial(k) for G in F])
    B=vec([S.eye(sz) for sz in sizes]); steps=[]; t0=time.time()
    while True:
        C=hermite_normal_form(S.Matrix.hstack(B,*[mul(B,g) for g in gens]))
        steps.append(C.cols)
        if C==B: break
        B=C
        if len(steps)>100: raise RuntimeError('No stabilization')
    D=smith_normal_form(B,domain=ZZ)
    diagonal=[abs(int(D[i,i])) for i in range(B.cols)]
    idx=math.prod(diagonal)
    expected=sum((d+1)**2 for d in range(n+1))
    assert B.cols==expected
    # Exact rational closure coefficient certificate for each generator.
    # HNF equality itself is the integral closure certificate.
    for g in gens:
        assert hermite_normal_form(S.Matrix.hstack(B,mul(B,g)))==B
    filename=f'order_basis_n{n}_{kind}.json'
    (ROOT/filename).write_text(json.dumps({'n':n,'kind':kind,'block_sizes':sizes,
        'basis_rows':B.tolist(),'smith_nonzero':diagonal,'index':str(idx),'closure_ranks':steps},default=int))
    row={'n':n,'kind':kind,'rank':B.cols,'ambient_full_rank':16**n,
         'saturation_index':str(idx),'prime_factors':str(S.factorint(idx)),
         'nonunit_smith':[d for d in diagonal if d!=1],
         'closure_ranks':steps,'seconds':round(time.time()-t0,3),'certificate':filename}
    print(json.dumps(row),flush=True)
    return row
if __name__=='__main__':
    import argparse
    ap=argparse.ArgumentParser();ap.add_argument('--n',type=int,nargs='*',default=[1,2,3,4]);ap.add_argument('--kinds',nargs='*',default=['ordinary','ordinary_pi','divided','divided_pi']);args=ap.parse_args()
    out=[]
    for n in args.n:
        for kind in args.kinds: out.append(one(n,kind))
    (ROOT/('exterior_order_results_'+''.join(map(str,args.n))+'.json')).write_text(json.dumps(out,indent=2))
