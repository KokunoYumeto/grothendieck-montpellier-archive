#!/usr/bin/env python3
"""Horizontal H1 test for the differential PD image of a standard tail.

D_N is the sub-DGA of F generated by S and all degree-zero functions
of weight>=N. In form degree1 it consists exactly of sums a df, with
f of weight>=N and a either a coefficient or of weight>=N.
In simplicial degree1 it is all F^1 in those weights. This calculates
the image of the alternating face map from simplicial degree2.
All calculations are exact mod p; no normalized-kernel inference is
needed, because D_N^1 at simplicial degree0 is zero.
"""
from math import comb
from pathlib import Path
import json,time
start=time.perf_counter()

def compositions(n):
    return [(a,b,n-a-b) for a in range(n+1) for b in range(n-a+1)]

def face(e,i):
    t,x,y=e
    if i==0:return comb(t+x,t),(t+x,y)
    if i==1:return comb(x+y,x),(t,x+y)
    if y:return 0,(0,0)
    return 1,(t,x)

def column(a,f,w,p):
    v=[0]*w
    for i in range(3):
        ca,aa=face(a,i);cf,ff=face(f,i)
        if not ca or not cf or not ff[1]:continue
        k=aa[1]+ff[1]-1
        coefficient=ca*cf*comb(aa[0]+ff[0],aa[0])*comb(k,aa[1])
        v[k]=(v[k]+(-1)**i*coefficient)%p
    return v

def insert(v,B,p):
    v=list(v)
    for j,b in sorted(B.items()):
        c=v[j]
        if c:v=[(a-c*z)%p for a,z in zip(v,b)]
    if not any(v):return False
    j=next(j for j,a in enumerate(v) if a)
    u=pow(v[j],-1,p);B[j]=[(u*a)%p for a in v]
    return True

results=[]
for N in [2,3,4]:
    for p in [2,3,5,7]:
        for w in range(N,25):
            B={};gens=0
            for a in range(w-N+1):
                aa=compositions(a) if a>=N else [(a,0,0)]
                for av in aa:
                    for fv in compositions(w-a):
                        gens+=1;insert(column(av,fv,w,p),B,p)
                        if len(B)==w:break
                    if len(B)==w:break
                if len(B)==w:break
            results.append({'N':N,'p':p,'weight':w,'rank_boundary':len(B),
                            'H1_dimension':w-len(B),'generators_processed':gens,
                            'boundary_basis':B if w-len(B) else {}})
out={'description':__doc__,'cases':results,
     'elapsed_seconds':time.perf_counter()-start}
Path('SA08_work/logs/D_tail_differential_image.json').write_text(json.dumps(out,indent=2)+'\n')
nonzero=[{k:r[k] for k in ['N','p','weight','H1_dimension']} for r in results if r['H1_dimension']]
print(json.dumps({'cases':len(results),'elapsed_seconds':out['elapsed_seconds'],'nonzero':nonzero}))
