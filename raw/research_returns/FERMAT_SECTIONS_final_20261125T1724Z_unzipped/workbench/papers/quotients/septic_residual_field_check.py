#!/usr/bin/env python3
"""Exact polynomial checks for the septic residual field.

The checks establish polynomial identities used in the paper. They do
not compute or certify a class number. Generated by GPT-6 Astra Pro.
"""
from pathlib import Path
import hashlib
import json
import sympy as sp

z,x,Z=sp.symbols('z x Z')
phi=sum(z**i for i in range(7))
alpha=(1-z)*(1-z**4)*(1-z**5)
def red(poly):
    return sp.rem(sp.Poly(poly,z,modulus=3),sp.Poly(phi,z,modulus=3)).as_expr()

assert red(alpha**2+z**3)==0
assert red(alpha**14+1)==0
assert red(alpha**28-1)==0
assert sp.gcd(325,728)==13
assert ((324**6-1)//7)%7==0
assert 3**21*7**22<16**24

f=3*x**4-3*x**3-12*x**2-12*x-1
g=4*x**3-3*x**2-8*x-4
R=27*Z**8-1323*Z**6+6174*Z**4-117649
resultant=sp.resultant(f,Z**2-g,x)
assert sp.expand(resultant-R)==0
a=-36*Z**4+1323*Z**2-4116
b=9*Z**4+588*Z**2+1029
subs=sp.subresultants(f,Z**2-g,x)
assert any(sp.expand(s-(a*x+b))==0 for s in subs)
assert sp.degree(sp.gcd(a,R),Z)==0
recovered=sp.together(f.subs(x,-b/a))
assert sp.rem(sp.fraction(recovered)[0],R,Z)==0
recovered=sp.together((Z**2-g).subs(x,-b/a))
assert sp.rem(sp.fraction(recovered)[0],R,Z)==0

here=Path(__file__)
out={
    'model':'GPT-6 Astra Pro',
    'exact_arithmetic':'SymPy polynomials over Z and F3',
    'sympy_version':sp.__version__,
    'alpha_reduction':str(red(alpha)),
    'resultant':str(R),
    'subresultant':str(a*x+b),
    'class_group_computed':False,
    'assertions_passed':True,
    'script_sha256':hashlib.sha256(here.read_bytes()).hexdigest(),
}
here.with_suffix('.json').write_text(json.dumps(out,indent=2)+'\n')
print(json.dumps(out,indent=2))
