"""Regenerate the main-paper inclusion from the complete branch source."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = root/'branches'/'plethysm'/'PLETHYSM_STANDALONE.tex'
text = source.read_text()
text = text[text.index(r'\section{Conventions, source locators and status}'):]
text = text[:text.rindex(r'\end{document}')]

def expand(body, directory):
    def replace(match):
        target = directory/match.group(1)
        return '\n% Source: '+str(target.relative_to(root))+'\n'+expand(target.read_text(),target.parent)
    return re.sub(re.escape(chr(92)+'input{')+r'([^}]+)}', replace, body)

out = root/'branches'/'root'/'plethysm_integrated.tex'
out.write_text('% Generated by scripts/integrate_plethysm.py; edit original branch files.\n'+expand(text,source.parent))
print(out)
