#!/usr/bin/env python3
"""Independent full exterior-character certificate for the positive-rank variant.

The input on the principally polarized Jacobian is G=I_{Z_H}(Theta), with
ch(G)=1+theta-d theta^2/2-d theta^3/6.  The second input is (-1)^*G.
We reconstruct Psi=(id x FM_{P^{-1}})mu^* and then E=Psi(input)^vee[-1].
This script verifies characters and polarization identities only.  It makes no
claim that E is coherent, locally free, regular, or generated by sections.
"""
from fractions import Fraction as F
from math import factorial
from pathlib import Path
import json,hashlib
from semiregular_gaussian_certificate import (
    K,add,scale,wedge,power,exp2,pair,equal,one_plane,three_planes,qroot,serialize
)

def case(d):
    K.d=d;N=d+1;u=K(0,1);a=(K(1)+K(1)/u)/2;b=a.conj()
    for k,expected in enumerate([1,1,F(-d,2),F(-d,6)]):
        pu=K(1);mu=K(1)
        for _ in range(k):pu=pu*u;mu=mu*(-u)
        assert (a*pu+b*mu)/factorial(k)==expected
    transformed={}
    for r1,c1 in [(u,a),(-u,b)]:
        for r2,c2 in [(u,a),(-u,b)]:
            transformed=add(transformed,scale(three_planes(one_plane(r1,-r2)),c1*c2))
    # Derived dual multiplies codimension k by (-1)^k; [-1] adds -1.
    E={m:c*((-1)**(m.bit_count()//2+1)) for m,c in transformed.items()}
    theta={};that={};gamma={}
    for j in range(3):
        theta=add(theta,pair(4*j,4*j+1))
        that=add(that,pair(4*j+2,4*j+3))
        gamma=add(gamma,pair(4*j,4*j+3))
        gamma=add(gamma,scale(pair(4*j+1,4*j+2),-1))
    H=add(scale(theta,d),that)
    t=scale(add(qroot(u),qroot(-u)),-a*b)
    pc=[F(8*d),F(2*(d-1)),F(-1),F(-(d-1),12*d),F(1,48*d),F(d-1,960*d*d),F(-1,5760*d*d)]
    P={}
    for k,c in enumerate(pc):P=add(P,scale(power(H,k),c))
    normalized=wedge(exp2(scale(gamma,F(1,2)),6),E)
    assert equal(normalized,add(t,P))
    assert E[0]==8*d
    assert all(c.b==0 for c in E.values()) and all(c.b==0 for c in t.values())
    assert equal(wedge(H,t),{})
    assert equal(power(t,2),{4095:K(-8*d*N*N)})
    c1=add(scale(gamma,-4*d),scale(H,2*(d-1)))
    assert equal({m:c for m,c in E.items() if m.bit_count()==2},c1)
    kappa=wedge(exp2(scale(c1,F(-1,8*d)),6),E)
    kpoly=wedge(exp2(scale(H,F(-(d-1),4*d)),6),P)
    assert equal(kappa,add(t,kpoly))
    k3={m:c for m,c in kappa.items() if m.bit_count()==6}
    assert equal(k3,add(t,scale(power(H,3),F((d-1)*N*N,24*d*d))))
    payload=serialize(normalized)
    return {'d':d,'N':N,'rank':8*d,'P_coefficients':[str(c) for c in pc],
            'full_character_equal':True,'kappa_equal':True,'H_times_weil_zero':True,
            'weil_self_square':-8*d*N*N,'kappa3_polarization_coefficient':str(F((d-1)*N*N,24*d*d)),
            'character_coefficient_count':len(E),'weil_coefficient_count':len(t),
            'normalized_character_sha256':hashlib.sha256(json.dumps(payload,separators=(',',':')).encode()).hexdigest(),
            'normalized_character':payload,'weil_character':serialize(t)}

if __name__=='__main__':
    out={'scope':__doc__,'cases':[case(d) for d in [4,8,12,16,28,44,76,172,268,652]]}
    Path(__file__).with_suffix('.json').write_text(json.dumps(out,indent=2)+'\n')
    for c in out['cases']:print({k:c[k] for k in ['d','N','rank','full_character_equal','kappa_equal','weil_self_square','normalized_character_sha256']})
