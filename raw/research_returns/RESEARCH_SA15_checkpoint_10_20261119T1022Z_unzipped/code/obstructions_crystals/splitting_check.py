"""Exact mod-p certificates for necessary Steinberg lifting relations.

No group-presentation sufficiency is assumed: a positive case is checked by
enumerating the group generated by the lifted elementary matrices.
"""
import itertools, json, time, pathlib
import numpy as np

OUT=pathlib.Path(__file__).resolve().parent

def relations(n,p):
    pairs=[(i,j) for i in range(n) for j in range(n) if i!=j]
    ix={v:i for i,v in enumerate(pairs)}
    rel=[]
    for a in range(len(pairs)): rel.append(([a]*p,[],f'order {pairs[a]}'))
    for a,(i,j) in enumerate(pairs):
        for b,(k,l) in enumerate(pairs):
            if j!=k and i!=l: rel.append(([a,b],[b,a],f'commute {(i,j),(k,l)}'))
    for i,j,k in itertools.permutations(range(n),3):
        a,b,c=ix[i,j],ix[j,k],ix[i,k]
        rel.append(([a,b],[b,a,c],f'Steinberg {(i,j,k)}'))
    base=[]
    for i,j in pairs:
        a=np.eye(n,dtype=np.int64);a[i,j]+=1;base.append(a)
    N=len(pairs)*n*n
    def prod(word):
        r=np.eye(n,dtype=np.int64)
        for a in word:r=r@base[a]
        return r
    def derivative(word):
        ans=np.zeros((n,n,N),dtype=np.int64)
        for t,a in enumerate(word):
            left=prod(word[:t]);right=prod(word[t+1:])
            for i in range(n):
                for j in range(n):
                    ans[:,:,a*n*n+i*n+j]+=np.outer(left[:,i],right[j,:])
        return ans
    A=[];b=[];names=[]
    for w,v,name in rel:
        diff=prod(w)-prod(v)
        assert not np.any(diff%p)
        der=derivative(w)-derivative(v)
        for i in range(n):
            for j in range(n):
                A.append(der[i,j,:]%p);b.append((-diff[i,j]//p)%p)
                names.append(name+f' entry {i},{j}')
    return pairs,base,np.array(A,dtype=np.int64),np.array(b,dtype=np.int64),names

def solve(A,b,p):
    aug=np.column_stack([A,b]).copy()%p
    cert=np.eye(len(b),dtype=np.int64)
    piv=[];r=0
    for c in range(A.shape[1]):
        candidates=np.flatnonzero(aug[r:,c])
        if len(candidates)==0:continue
        j=r+int(candidates[0])
        aug[[r,j]]=aug[[j,r]];cert[[r,j]]=cert[[j,r]]
        inv=pow(int(aug[r,c]),-1,p)
        aug[r]=aug[r]*inv%p;cert[r]=cert[r]*inv%p
        for j in range(len(b)):
            if j!=r and aug[j,c]:
                q=int(aug[j,c]);aug[j]=(aug[j]-q*aug[r])%p;cert[j]=(cert[j]-q*cert[r])%p
        piv.append(c);r+=1
    bad=[j for j in range(r,len(b)) if aug[j,-1]]
    if bad:
        w=cert[bad[0]]
        assert np.all((w@A)%p==0) and int(w@b)%p!=0
        return r,None,{str(i):int(v) for i,v in enumerate(w) if v}
    x=np.zeros(A.shape[1],dtype=np.int64)
    for i,c in enumerate(piv):x[c]=aug[i,-1]
    assert np.all((A@x-b)%p==0)
    return r,x,None

def closure(gens,q,limit=50000):
    n=len(gens[0]);one=tuple(np.eye(n,dtype=int).flat)
    known={one};queue=[one]
    for a in queue:
        a=np.array(a).reshape((n,n))
        for g in gens:
            b=tuple((a@g%q).flat)
            if b not in known:
                known.add(b);queue.append(b)
                if len(known)>limit:raise RuntimeError('closure limit exceeded')
    reductions={tuple(v%int(q**.5) for v in a) for a in known}
    return len(known),len(reductions)

def main():
    started=time.perf_counter();result={}
    for n,p in [(3,2),(3,3),(4,2)]:
        pairs,base,A,b,names=relations(n,p)
        rank,x,cert=solve(A,b,p)
        rec={'equations':len(b),'variables':A.shape[1],'rank':rank,'consistent':x is not None}
        if cert is not None:
            data={'n':n,'p':p,'nonzero_weights':cert,'rhs':sum(v*int(b[int(i)]) for i,v in cert.items())%p,'equation_names':{i:names[int(i)] for i in cert}}
            (OUT/f'certificate_n{n}_p{p}.json').write_text(json.dumps(data,indent=2))
            rec['certificate']=f'certificate_n{n}_p{p}.json'
        else:
            gens=[(a+p*x[t*n*n:(t+1)*n*n].reshape(n,n))%(p*p) for t,a in enumerate(base)]
            order,red=closure(gens,p*p)
            rec.update({'generators':[a.tolist() for a in gens],'order':order,'reduction_order':red})
        result[f'n={n},p={p}']=rec
    gens3=[np.array([[1,1],[6,7]]),np.array([[0,4],[7,0]])]
    result['GL2_Z9']={'generators':[a.tolist() for a in gens3], 'orders':closure(gens3,9),'determinants':[int(a[0,0]*a[1,1]-a[0,1]*a[1,0])%9 for a in gens3]}
    gens2=[np.array([[0,1],[1,0]]),np.array([[0,-1],[1,-1]])]
    result['GL2_Z4']={'generators':[a.tolist() for a in gens2], 'orders':closure(gens2,4)}
    u=np.array([[1,1],[0,1]]);lifts=[]
    for t in itertools.product(range(2),repeat=4):
        a=u+2*np.array(t).reshape(2,2)
        if int(a[0,0]*a[1,1]-a[0,1]*a[1,0])%4==1:
            lifts.append({'matrix':(a%4).tolist(),'square':(a@a%4).tolist()})
    assert all(a['square']!=[[1,0],[0,1]] for a in lifts)
    result['SL2_Z4_transvection_lifts']=lifts
    result['seconds']=time.perf_counter()-started
    (OUT/'splitting_output.json').write_text(json.dumps(result,indent=2))
    print(json.dumps(result,indent=2))
if __name__=='__main__':main()
