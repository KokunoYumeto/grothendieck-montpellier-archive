"""Exact corroboration of K17-K12-R8-NONSIMPLICIAL.

The classification and index bounds are cited source inputs, not computed
by this file. All matrix/glue arithmetic here uses integers and Fraction.
"""
from fractions import Fraction as F
from itertools import product
from pathlib import Path
from collections import Counter
import ast
import hashlib
import json


def transpose(a):
    return [list(x) for x in zip(*a)]


def multiply(a, b):
    return [[sum(x*y for x, y in zip(row, col)) for col in zip(*b)]
            for row in a]


def matvec(a, x):
    return tuple(sum(y*z for y, z in zip(row, x)) for row in a)


def rref(a):
    a = [list(map(F, row)) for row in a]
    pivots = []
    for j in range(len(a[0])):
        i = next((i for i in range(len(pivots), len(a)) if a[i][j]), None)
        if i is None:
            continue
        r = len(pivots)
        a[r], a[i] = a[i], a[r]
        p = a[r][j]
        a[r] = [x/p for x in a[r]]
        for i in range(len(a)):
            if i != r:
                p = a[i][j]
                a[i] = [x-p*y for x, y in zip(a[i], a[r])]
        pivots.append(j)
        if len(pivots) == len(a):
            break
    return a, pivots


def determinant(a):
    a = [list(map(F, row)) for row in a]
    det = F(1)
    for j in range(len(a)):
        i = next((i for i in range(j, len(a)) if a[i][j]), None)
        if i is None:
            return F(0)
        if i != j:
            a[i], a[j] = a[j], a[i]
            det = -det
        p = a[j][j]
        det *= p
        for i in range(j+1, len(a)):
            t = a[i][j]/p
            a[i] = [x-t*y for x, y in zip(a[i], a[j])]
    return det


def inverse(a):
    n = len(a)
    result, pivots = rref([row+[int(i == j) for j in range(n)]
                          for i, row in enumerate(a)])
    assert pivots == list(range(n))
    return [row[n:] for row in result]


def quadratic(v):
    return tuple(v[i]*v[j] for i in range(len(v)) for j in range(i, len(v)))


def canonical(v):
    return tuple(v) if next(x for x in v if x) > 0 else tuple(-x for x in v)


def sign(perm):
    return (-1)**sum(perm[i] > perm[j] for i in range(len(perm))
                    for j in range(i+1, len(perm)))


units = [tuple(int(i == j) for i in range(6)) for j in range(6)]
e = units[5]
frame = [units[0], units[1]] + [tuple(a-b for a, b in zip(e, units[j]))
                                for j in (2, 3, 4)]
frame += [(-1, -1, 1, 1, 1, 0)]
other = [tuple(a-b for a, b in zip(e, v)) for v in frame]
rays = frame + other
fm = transpose(frame)
assert tuple(sum(v[j] for v in frame) for j in range(6)) == tuple(3*x for x in e)
assert abs(determinant(fm)) == 3
assert all(sum(quadratic(v)[j] for v in frame) == sum(quadratic(v)[j] for v in other)
           for j in range(21))
assert len(rref(transpose([quadratic(v) for v in rays]))[1]) == 11
# The model lattice generated by the rays is exactly Z^6: e1,...,e5
# occur up to sign, and e6 is a sum of a frame ray and its partner.
ray_set = set(map(canonical, rays))
assert all(canonical(v) in ray_set for v in units[:5])
assert all(a+b == c for a, b, c in zip(frame[0], other[0], e))
fm_inv = inverse(fm)
involution = [[-int(i == j) + e[i]*[1, 1, 1, 1, 1, 2][j]
               for j in range(6)] for i in range(6)]
assert multiply(involution, involution) == [[int(i == j) for j in range(6)] for i in range(6)]
assert [matvec(involution, v) for v in frame] == other
assert matvec(involution, e) == e


def orientation(a):
    assert all(F(x).denominator == 1 for row in a for x in row)
    assert abs(determinant(a)) == 1
    lookup = {canonical(v): i for i, v in enumerate(rays)}
    perm = [lookup[canonical(matvec(a, v))] for v in rays]
    relation = [1]*6 + [-1]*6
    transported = [0]*12
    for i, j in enumerate(perm):
        transported[j] = relation[i]
    if transported == relation:
        relation_sign = 1
    else:
        assert transported == [-x for x in relation]
        relation_sign = -1
    return sign(perm)*relation_sign


assert orientation(involution) == -1
cases = []
for bits in product((0, 1), repeat=6):
    u = tuple(sum(bits[i]*frame[i][j] for i in range(6)) for j in range(6))
    k = sum(bits)
    for outside in ((1, 0), (0, 1), (1, 1)):
        row = {'core_bits': bits, 'outside_bits': outside, 'core_weight': k}
        if outside == (1, 1):
            row.update(result='odd', map='outside swap')
        elif k in (1, 5):
            i = bits.index(1 if k == 1 else 0)
            m = frame[i] if k == 1 else other[i]
            assert all((x-y) % 2 == 0 for x, y in zip(m, u))
            row.update(result='impossible', minimum_representative=m,
                       reason='Two nonzero half-sum vectors have total norm one.')
        else:
            a = involution
            perm = list(range(6))
            if k == 3:
                support = [i for i in range(6) if bits[i]]
                complement = [i for i in range(6) if not bits[i]]
                for i, j in zip(support, complement):
                    perm[i], perm[j] = j, i
                permutation_map = multiply(transpose([frame[j] for j in perm]), fm_inv)
                assert orientation(permutation_map) == 1
                a = multiply(permutation_map, involution)
            assert orientation(a) == -1
            assert all((x-y) % 2 == 0 for x, y in zip(matvec(a, u), u))
            row.update(result='odd', map='permutation times core involution',
                       frame_permutation=perm,
                       core_matrix=[[int(x) for x in r] for r in a])
        cases.append(row)
counts = dict(Counter(row['result'] for row in cases))
