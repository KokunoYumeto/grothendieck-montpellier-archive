"""Exact exploration and closure certificates for the pro-2 tripod image.

All operations take place in the free associative algebra over Q, truncated
by arithmetic weight.  A group generator is stored by its Lie logarithm.
Elimination uses only Z_2 powers (rational exponents of nonnegative 2-valuation).
Final closure checks certify the compact subgroup generated by h and its
Gamma orbit, subject to the mathematical Malcev-collection lemma in the
accompanying notes.  This is not a formal proof checker.
"""
from fractions import Fraction as F
from itertools import product, combinations
from functools import lru_cache
from math import factorial
from pathlib import Path
import argparse
import hashlib
import json
import time


def v2(x):
    x=F(x)
    if not x:
        return 10**9
    def val(n):
        n=abs(n)
        return (n & -n).bit_length()-1
    return val(x.numerator)-val(x.denominator)


def pow2(n):
    return F(2**n) if n>=0 else F(1,2**(-n))


def is_lyndon(w):
    return bool(w) and all(w<w[i:] for i in range(1,len(w)))


class Algebra:
    def __init__(self,W,u=5):
        self.W=W
        self.u=u
        self.letters=list(range(3,W+1,2))
        self.words=[w for r in range(1,W//3+1)
                    for w in product(self.letters,repeat=r) if sum(w)<=W]
        self.lyndon=sorted((w for w in self.words if is_lyndon(w)),
                          key=lambda w:(sum(w),w))
        self.order=sorted(self.lyndon,
                          key=lambda w:(sum(w),len(w)!=1,w))
        self.order_index={w:i for i,w in enumerate(self.order)}
        self.byweight={n:[w for w in self.lyndon if sum(w)==n]
                       for n in range(1,W+1)}
        self.a={(m,):F(1) for m in self.letters}
        self.stats={'bch':0,'commutator':0,'D':0,'D_inverse':0}

    @staticmethod
    def clean(x):
        return {w:F(c) for w,c in x.items() if c}

    def add(self,*args):
        out={}
        for x in args:
            for w,c in x.items():
                out[w]=out.get(w,F(0))+c
        return self.clean(out)

    def scale(self,x,c):
        c=F(c)
        return {w:c*a for w,a in x.items() if c*a}

    def mul(self,x,y):
        out={}
        for v,a in x.items():
            for w,b in y.items():
                if sum(v)+sum(w)<=self.W:
                    z=v+w
                    out[z]=out.get(z,F(0))+a*b
        return self.clean(out)

    def bracket(self,x,y):
        return self.add(self.mul(x,y),self.scale(self.mul(y,x),-1))

    def exp(self,x):
        assert () not in x
        out={():F(1)}
        power={():F(1)}
        for n in range(1,self.W//3+1):
            power=self.mul(power,x)
            if not power:
                break
            out=self.add(out,self.scale(power,F(1,factorial(n))))
        return out

    def log(self,g):
        assert g.get((),F(0))==1
        x=dict(g)
        del x[()]
        out={}
        power={():F(1)}
        for n in range(1,self.W//3+1):
            power=self.mul(power,x)
            if not power:
                break
            out=self.add(out,self.scale(power,F((-1)**(n+1),n)))
        return out

    def bch(self,x,y):
        self.stats['bch']+=1
        if not x:
            return dict(y)
        if not y:
            return dict(x)
        return self.log(self.mul(self.exp(x),self.exp(y)))

    def commutator(self,x,y):
        self.stats['commutator']+=1
        if min(map(sum,x),default=self.W+1)+min(map(sum,y),default=self.W+1)>self.W:
            return {}
        return self.log(self.mul(self.mul(self.mul(self.exp(x),self.exp(y)),
                                          self.exp(self.scale(x,-1))),
                                 self.exp(self.scale(y,-1))))

    def D(self,x):
        self.stats['D']+=1
        term={w:c*self.u**sum(w) for w,c in x.items()}
        out=dict(term)
        minus_half_a=self.scale(self.a,F(-1,2))
        for n in range(1,self.W//3+1):
            term=self.bracket(minus_half_a,term)
            if not term:
                break
            out=self.add(out,self.scale(term,F(1,factorial(n))))
        return out

    def D_inverse(self,x):
        self.stats['D_inverse']+=1
        term=dict(x)
        out=dict(term)
        half_a=self.scale(self.a,F(1,2))
        for n in range(1,self.W//3+1):
            term=self.bracket(half_a,term)
            if not term:
                break
            out=self.add(out,self.scale(term,F(1,factorial(n))))
        return {w:c/F(self.u**sum(w)) for w,c in out.items()}

    @lru_cache(None)
    def hall(self,w):
        if len(w)==1:
            return {w:F(1)}
        for i in range(1,len(w)):
            if is_lyndon(w[i:]):
                assert is_lyndon(w[:i])
                return self.bracket(self.hall(w[:i]),self.hall(w[i:]))
        raise AssertionError(w)

    def coords(self,x):
        rem=dict(x)
        out={}
        for w in self.lyndon:
            c=rem.get(w,F(0))
            if c:
                out[w]=c
                rem=self.add(rem,self.scale(self.hall(w),-c))
        assert not rem, ('not a Lie polynomial',rem)
        return out

    def first(self,x):
        cs=self.coords(x)
        if not cs:
            return None,None
        w=min(cs,key=self.order_index.__getitem__)
        return w,cs[w]

    def weightpart(self,x,n):
        return {w:c for w,c in x.items() if sum(w)==n}

    @staticmethod
    def encode(x):
        return {','.join(map(str,w)):str(c) for w,c in sorted(x.items())}


class Closure:
    def __init__(self,alg):
        self.A=alg
        self.basis={}
        self.events=[]
        self.reductions=0

    def ordered(self):
        return sorted(self.basis,key=self.A.order_index.__getitem__)

    def reduce(self,x,mutate=False,origin=''):
        x=dict(x)
        coordinates=[]
        changed=False
        while x:
            self.reductions+=1
            w,c=self.A.first(x)
            assert w is not None
            if w not in self.basis:
                if not mutate:
                    return x,coordinates,changed
                val=v2(c)
                q=pow2(val)/c
                assert v2(q)==0
                self.basis[w]=self.A.scale(x,q)
                self.events.append({'pivot':w,'valuation':val,'action':'add','origin':origin})
                return {},coordinates,True
            b=self.basis[w]
            _,bc=self.A.first(b)
            if v2(c)<v2(bc):
                if not mutate:
                    return x,coordinates,changed
                old=b
                val=v2(c)
                q=pow2(val)/c
                assert v2(q)==0
                self.basis[w]=self.A.scale(x,q)
                self.events.append({'pivot':w,'valuation':val,'action':'replace','origin':origin})
                x=old
                changed=True
                continue
            q=c/bc
            assert v2(q)>=0
            coordinates.append((w,q))
            x=self.A.bch(self.A.scale(b,-q),x)
        return {},coordinates,changed

    def run(self,max_rounds=100):
        self.reduce(self.A.a,True,'h')
        rounds=[]
        for r in range(max_rounds):
            before=len(self.events)
            snapshot=[(w,dict(self.basis[w])) for w in self.ordered()]
            for w,b in snapshot:
                self.reduce(self.A.D(b),True,'D'+str(w))
            snapshot=[(w,dict(self.basis[w])) for w in self.ordered()]
            for (w,b),(v,c) in combinations(snapshot,2):
                if sum(w)+sum(v)<=self.A.W:
                    self.reduce(self.A.commutator(b,c),True,'comm'+str((w,v)))
            rounds.append({'round':r,'events':len(self.events)-before,'rank':len(self.basis)})
            if len(self.events)==before:
                self.verify()
                return rounds
        raise RuntimeError('No stabilization')

    def verify(self):
        assert len(self.basis)==len(self.A.order), (len(self.basis),len(self.A.order))
        assert not self.reduce(self.A.a)[0]
        keys=self.ordered()
        for w in keys:
            assert not self.reduce(self.A.D(self.basis[w]))[0], ('D',w)
            assert not self.reduce(self.A.D_inverse(self.basis[w]))[0], ('D_inverse',w)
        for w,v in combinations(keys,2):
            if sum(w)+sum(v)<=self.A.W:
                assert not self.reduce(self.A.commutator(self.basis[w],self.basis[v]))[0], ('comm',w,v)


def determinant(mat):
    a=[list(map(F,row)) for row in mat]
    d=F(1)
    for j in range(len(a)):
        k=next((k for k in range(j,len(a)) if a[k][j]),None)
        if k is None:
            return F(0)
        if k!=j:
            a[j],a[k]=a[k],a[j]
            d=-d
        p=a[j][j]
        d*=p
        for i in range(j+1,len(a)):
            q=a[i][j]/p
            for k in range(j+1,len(a)):
                a[i][k]-=q*a[j][k]
            a[i][j]=F(0)
    return d


def analyze(W):
    start=time.monotonic()
    A=Algebra(W)
    H=Closure(A)
    rounds=H.run()
    sigma={m:A.weightpart(H.basis[(m,)],m) for m in A.letters}

    @lru_cache(None)
    def odd_hall(w):
        if len(w)==1:
            return sigma[w[0]]
        for i in range(1,len(w)):
            if is_lyndon(w[i:]):
                return A.bracket(odd_hall(w[:i]),odd_hall(w[i:]))
        raise AssertionError(w)

    graded=[]
    for n in range(1,W+1):
        ws=A.byweight[n]
        if not ws:
            continue
        actual=[A.coords(A.weightpart(H.basis[w],n)) for w in ws]
        generated=[A.coords(odd_hall(w)) for w in ws]
        da=determinant([[row.get(v,F(0)) for v in ws] for row in actual])
        dg=determinant([[row.get(v,F(0)) for v in ws] for row in generated])
        assert da and dg
        index=v2(dg/da)
        assert index>=0
        graded.append({'weight':n,'rank':len(ws),'hall_words':ws,
                       'actual_determinant_v2':v2(da),
                       'odd_generated_determinant_v2':v2(dg),
                       'index_v2':index,
                       'actual_rows':[[str(row.get(v,F(0))) for v in ws] for row in actual],
                       'odd_generated_rows':[[str(row.get(v,F(0))) for v in ws] for row in generated]})
    result={'weight_cutoff':W,'u':5,'dimension':len(A.order),
            'rounds':rounds,'events':H.events,
            'pivots':[{'word':w,'weight':sum(w),'valuation':v2(A.first(H.basis[w])[1])}
                      for w in H.ordered()],
            'basis_logarithms':{','.join(map(str,w)):A.encode(H.basis[w]) for w in H.ordered()},
            'primitive_odd_graded':{str(m):A.encode(sigma[m]) for m in A.letters},
            'graded':graded,'closure_checks':'passed exactly',
            'operations':A.stats,'reductions':H.reductions,
            'seconds':time.monotonic()-start}
    return result


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('weights',nargs='*',type=int,default=[8,10,12,14])
    parser.add_argument('--output',default='work/pro2_integral_malcev_results.json')
    args=parser.parse_args()
