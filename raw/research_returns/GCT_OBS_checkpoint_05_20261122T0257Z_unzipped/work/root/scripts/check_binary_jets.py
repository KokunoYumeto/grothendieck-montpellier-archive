#!/usr/bin/env python3
"""Exact finite-field certificates for binary transverse determinant jets.

Only Python's standard library is required.  The pencil is
  x0 I + x1 diag(1,...,n) + x2 A + x3 B,
where A,B are generated by the explicitly specified integer recurrence.
The adjugate is generated from the characteristic-polynomial recurrence,
with division by 1,...,n-1 in F_p (p>n).

Usage: python check_binary_jets.py 9 5 --output result.json
       python check_binary_jets.py 23 9 --output result23.json
"""
import argparse
import hashlib
import json
import time


def pencil(n, p, seed):
    state = seed
    matrices = []
    for _ in range(2):
        row = []
        for _ in range(n*n):
            state = (1664525*state + 1013904223) % 2**32
            row.append((state >> 16) % p)
        matrices.append(row)
    return matrices


def matmul(a, b, n, p):
    bt = [b[j::n] for j in range(n)]
    return [sum(x*y for x, y in zip(a[i*n:(i+1)*n], col)) % p
            for i in range(n) for col in bt]


def adjugate(n, cutoff, p, seed):
    """Dictionary of coefficients of adj(I+xA1+yA2+zA3)."""
    a, b = pencil(n, p, seed)
    identity = [int(i == j) for i in range(n) for j in range(n)]
    coefficients = {(0, 0, 0): identity}
    previous = {(0, 0, 0): identity}
    for degree in range(1, n):
        current = {}
        for y in range(min(degree, cutoff)+1):
            for z in range(min(degree-y, cutoff-y)+1):
                x = degree-y-z
                v = [0]*(n*n)
                if x:
                    c = previous[(x-1, y, z)]
                    v = [(i+1)*c[i*n+j] for i in range(n) for j in range(n)]
                if y:
                    c = matmul(a, previous[(x, y-1, z)], n, p)
                    v = [u+w for u, w in zip(v, c)]
                if z:
                    c = matmul(b, previous[(x, y, z-1)], n, p)
                    v = [u+w for u, w in zip(v, c)]
                e = sum(v[i*n+i] for i in range(n))*pow(degree, -1, p) % p
                current[(x, y, z)] = [(e*(i == j)-v[i*n+j]) % p
                    for i in range(n) for j in range(n)]
        coefficients.update(current)
        previous = current
    return coefficients


def jacobian(n, cutoff, p, seed):
    adj = adjugate(n, cutoff, p, seed)
    rows, labels = [], []
    zero = [0]*(n*n)
    for total in range(n+1):
        for y in range(min(total, cutoff)+1):
            for z in range(min(total-y, cutoff-y)+1):
                x = total-y-z
                alpha = (n-total, x, y, z)
                blocks = []
                for k in range(4):
                    reduced = list(alpha)
                    reduced[k] -= 1
                    c = zero if reduced[k] < 0 else adj.get(tuple(reduced[1:]), zero)
                    blocks.extend(c[j*n+i] for i in range(n) for j in range(n))
                rows.append(bytes(blocks))
                labels.append(alpha)
    return rows, labels


def rank_packed(matrix, p):
    """Exact Gaussian elimination using disjoint 32-bit integer lanes.

    Inputs and outputs of each reduction have all lanes in [0,p-1].
    Before reduction each lane is below p^2. For p<256 the reciprocal
    quotient underestimates floor(x/p) by at most one; the last mask
    performs the possible correction. No product reaches a lane boundary.
    """
    width = len(matrix[0])
    one = ((1 << (32*width))-1)//((1 << 32)-1)
    low = 255*one
    reciprocal = (1 << 16)//p
    offset = p*(p-1)*one

    def reduce(x):
        q = ((x*reciprocal) >> 16) & low
        r = x-p*q
        return r-p*(((r+(512-p)*one) >> 9) & one)

    a = [int.from_bytes(b''.join(int(x).to_bytes(4, 'little') for x in row),
                        'little') for row in matrix]
    rank, columns, determinant = 0, [], 1
    row_order = list(range(len(a)))
    for j in range(width):
        shift = 32*j
        pivot = next((i for i in range(rank, len(a))
                      if (a[i] >> shift) & 255), None)
        if pivot is None:
            continue
        if pivot != rank:
            a[rank], a[pivot] = a[pivot], a[rank]
            row_order[rank], row_order[pivot] = row_order[pivot], row_order[rank]
            determinant = -determinant % p
        value = (a[rank] >> shift) & 255
        determinant = determinant*value % p
        a[rank] = reduce(a[rank]*pow(value, -1, p))
        for i in range(rank+1, len(a)):
            value = (a[i] >> shift) & 255
            if value:
                a[i] = reduce(a[i]+offset-value*a[rank])
        columns.append(j)
        rank += 1
        if rank == len(a):
            break
    return rank, columns, determinant


def scalar_rank(a, p):
    a = [list(row) for row in a]
    rank = 0
    for j in range(len(a[0])):
        i = next((i for i in range(rank, len(a)) if a[i][j]), None)
        if i is None:
            continue
        a[rank], a[i] = a[i], a[rank]
        inv = pow(a[rank][j], -1, p)
        a[rank] = [x*inv % p for x in a[rank]]
        for i in range(rank+1, len(a)):
            c = a[i][j]
            a[i] = [(x-c*y) % p for x, y in zip(a[i], a[rank])]
        rank += 1
        if rank == len(a):
            break
    return rank


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('n', type=int)
    parser.add_argument('cutoff', type=int)
    parser.add_argument('--prime', type=int, default=101)
    parser.add_argument('--seed', type=int, default=20261122)
    parser.add_argument('--scalar', action='store_true')
    parser.add_argument('--output')
    args = parser.parse_args()
    assert args.n < args.prime < 256 and all(args.prime % d for d in range(2, int(args.prime**.5)+1))
    start = time.monotonic()
    matrix, labels = jacobian(args.n, args.cutoff, args.prime, args.seed)
    build_seconds = time.monotonic()-start
    rank, columns, det = rank_packed(matrix, args.prime)
    if args.scalar:
        assert scalar_rank(matrix, args.prime) == rank
    out = dict(n=args.n, cutoff=args.cutoff, prime=args.prime, seed=args.seed,
               shape=[len(matrix), len(matrix[0])], rank=rank,
               full_row_rank=rank == len(matrix), pivot_columns=columns,
               full_row_minor_determinant_mod_p=det if rank == len(matrix) else None,
               row_labels=labels,
               matrix_sha256=hashlib.sha256(b''.join(matrix)).hexdigest(),
               build_seconds=round(build_seconds, 3),
               elapsed_seconds=round(time.monotonic()-start, 3))
    if args.output:
        with open(args.output, 'w') as stream:
            json.dump(out, stream, indent=2)
            stream.write('\n')
    print(json.dumps({k:v for k,v in out.items() if k not in ('pivot_columns','row_labels')}))


if __name__ == '__main__':
    main()
