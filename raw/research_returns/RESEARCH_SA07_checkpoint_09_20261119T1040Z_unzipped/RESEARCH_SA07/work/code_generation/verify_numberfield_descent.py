assert forced == s.Matrix([[0,-2],[s.Rational(1,2),0]])
assert (quotient_matrix*s.Matrix([1,0])) % 2 == s.zeros(2,1)
assert (quotient_matrix*rotation*s.Matrix([1,0])) % 2 != s.zeros(2,1)
print("Fixed-Q quotient: E:y^2=x(x-1)(x-3), B:Y^2=X^3+8X^2+4X")
print("Exact quotient and translation identities, differential pullback verified")
print("Discriminants E,B and j(E):", delta_E, delta_B, j_E)
