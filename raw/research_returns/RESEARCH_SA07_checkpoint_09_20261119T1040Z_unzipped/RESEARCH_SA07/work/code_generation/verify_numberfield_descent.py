# E.2.18: exact Gaussian centralizer and determinant certificate.
cr, cs, ct, cu = s.symbols("cr cs ct cu")
general_matrix = s.Matrix([[cr,cs],[ct,cu]])
gaussian_j = s.Matrix([[0,-1],[1,0]])
centralizer_equations = list(general_matrix*gaussian_j-gaussian_j*general_matrix)
assert s.linsolve(centralizer_equations, (cr,cs,ct,cu)) == s.FiniteSet((cu,-ct,ct,cu))
gaussian_matrix = s.Matrix([[cr,-cs],[cs,cr]])
assert gaussian_matrix*gaussian_j == gaussian_j*gaussian_matrix
assert s.expand(gaussian_matrix.det()) == cr**2+cs**2
print("Gaussian centralizer: [[r,-s],[s,r]], determinant r^2+s^2")
print("An integral unimodular such matrix has determinant +1, forcing lambda^2=1")

