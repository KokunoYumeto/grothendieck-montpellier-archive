# Exact permutation computations for E.2.6; tuple entries use labels 0,1,2,3.
S4 = set(permutations(range(4)))
identity = tuple(range(4))
def compose(a, b):
    return tuple(a[b[i]] for i in range(4))
def inverse(a):
    return tuple(a.index(i) for i in range(4))
def sign(a):
    return (-1)**sum(a[i] > a[j] for i in range(4) for j in range(i+1, 4))
def closure(generators):
    generated = {identity}
    while True:
        enlarged = generated | {compose(a, b) for a in generated for b in generators}
        if enlarged == generated:
            return generated
        generated = enlarged
def commutator(a, b):
    return compose(compose(a, b), compose(inverse(a), inverse(b)))
c = (1, 0, 2, 3)
A4 = {a for a in S4 if sign(a) == 1}
V4 = {identity, (1, 0, 3, 2), (2, 3, 0, 1), (3, 2, 1, 0)}
assert closure({commutator(g, c) for g in S4}) == A4
assert closure({commutator(g, h) for g in A4 for h in A4}) == V4
residual = V4 | {compose(c, v) for v in V4}
assert len(residual) == 8 and closure(residual) == residual
real_swap = (1, 0, 3, 2)
assert real_swap in V4 and real_swap[2] == 3 and real_swap[3] == 2
print("Exact S4 certificate: subgroup generated by [g,c] is A4")
print("Exact A4 certificate: commutator subgroup is V4")
print("Residual preimage V4 union c*V4 has order8; (12)(34) swaps real roots3,4")

# E.2.13: an actual Q-defined quotient lattice not obtained by the
# specified admissible closure from H_1(E,Z).
eq_poly = x**3 - 4*x**2 + 3*x
q_X = x-4+3/x
q_Y_factor = 1-3/x**2
assert s.factor(eq_poly*q_Y_factor**2 -
                (q_X**3+8*q_X**2+4*q_X)) == 0
assert s.diff(q_X, x) == q_Y_factor
assert s.factor(q_X.subs(x, 3/x)-q_X) == 0
assert s.factor((-3/x**2)*q_Y_factor.subs(x, 3/x)-q_Y_factor) == 0
delta_E = 16*3**2*((-4)**2-4*3)
delta_B = 16*4**2*(8**2-4*4)
c4_E = 16*((-4)**2-3*3)
j_E = s.Rational(c4_E**3, delta_E)
