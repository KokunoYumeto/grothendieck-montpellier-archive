import sympy as s
from itertools import permutations

x = s.symbols("x")
j = 632000 + 282880 * s.sqrt(5)
a = -3 * j / (j - 1728)
b = -2 * j / (j - 1728)
computed_j = s.simplify(1728 * 4 * a**3 / (4 * a**3 + 27 * b**2))
assert s.simplify(computed_j - j) == 0
assert s.simplify(4 * a**3 + 27 * b**2) != 0
print("CM model: exact j-invariant verified, discriminant nonzero")
j_bar = 632000 - 282880 * s.sqrt(5)
class_polynomial = s.expand((x-j)*(x-j_bar))
print("Discriminant -20 class polynomial:", class_polynomial)
assert class_polynomial == x*x - 1264000*x - 681472000
print("The two real j-invariants are distinct:", s.simplify(j-j_bar))

f = s.Poly(x**3 - 4*x + 1, x, domain=s.QQ)
assert f.is_irreducible
disc = f.discriminant()
assert disc == 229 and not s.integer_nthroot(229, 2)[1]
intervals = f.intervals(eps=s.Rational(1,100))
assert len(intervals) == 3 and all(mult == 1 for _, mult in intervals)
print("Totally real excluded cubic:", f.as_expr())
print("Irreducible over Q:", f.is_irreducible)
print("Discriminant:", disc, "(positive, nonsquare)")
print("Certified three real root intervals:", intervals)
print("Therefore the normal closure has Galois group S3.")

# The explicit CM threefold lattice for the largest root theta.
C = s.Matrix([[0, 0, -1], [1, 0, 4], [0, 1, 0]])
T = s.Matrix(3, 3, lambda a, b: s.trace((C-s.eye(3)) * C**(a+b)))
assert T == s.Matrix([[-3, 8, -11], [8, -11, 35], [-11, 35, -52]])
Q = s.BlockMatrix([[s.zeros(3), 2*T], [-2*T, s.zeros(3)]]).as_explicit()
I = s.BlockMatrix([[s.zeros(3), -s.eye(3)], [s.eye(3), s.zeros(3)]]).as_explicit()
Theta = s.diag(C, C)
assert Q.T == -Q
assert T.det() == 458 and Q.det() == 3664**2
assert I*I == -s.eye(6)
assert Theta**3-4*Theta+s.eye(6) == s.zeros(6)
assert I*Theta == Theta*I
assert Theta.T*Q == Q*Theta
assert I.T*Q == -Q*I
assert all(b < 1 for ((a,b),m) in intervals[:2])
assert intervals[2][0][0] > 1
print("CM threefold trace matrix T:", T.tolist())
print("det(T), det(Q):", T.det(), Q.det())
print("Exact Rosati identities: theta*=theta and i*=-i verified")
print("Certified signs of theta-1 at ascending real roots: (-1,-1,+1)")
print("CM type traces: t_Phi(i)=-i, t_Phi(i*theta)=2*i*theta")

