 simple=[]
 for i in range(8):
  e=S.zeros(1,8);e[i]=1;simple.append(identity-cartan[:,i]*e)
 roots=[tuple(int(x) for x in cartan[:,i]) for i in range(8)]
 seen=set(roots)
 for root in roots:
  v=S.Matrix(root)
  for M in simple:
   r=tuple(int(x) for x in M*v)
   if r not in seen:seen.add(r);roots.append(r)
 assert len(roots)==240 and all((S.Matrix(r).T*gram*S.Matrix(r))[0]==2 for r in roots)
 ri={r:i for i,r in enumerate(roots)}
 def perm(M,phase=0):
  out=[]
  for source_phase in range(2):
   for root in roots:
    r=M*S.Matrix(root);dest_phase=source_phase+phase
    if dest_phase>=2:r=-r;dest_phase-=2
    out.append(240*dest_phase+ri[tuple(int(x) for x in r)])
  return Permutation(out)
 pabc=[perm(M) for M in [a,b,c]]
 ptuple=[perm(M,p) for M,p in zip(underlying,phases)]
 psimple=[perm(M) for M in simple]
 standard_weyl=PermutationGroup(psimple)
 standard_weyl.schreier_sims()
 assert all(standard_weyl.contains(p) for p in pabc)
 standard_extended=PermutationGroup(psimple+[perm(identity,1)])
 standard_extended.schreier_sims()
 assert all(standard_extended.contains(p) for p in ptuple)
 print('integer matrices, root orbit240, product and codimensions PASS',flush=True)
 order_abc=PermutationGroup(pabc).order()
 print('order generated by a,b,c',order_abc,flush=True)
 order_tuple=PermutationGroup(ptuple).order()
 print('order generated by the12tuple',order_tuple,flush=True)
 order_reflections=PermutationGroup(ptuple[:10]).order()
 assert order_abc==696729600 and order_tuple==1393459200 and order_reflections==51840
 assert standard_weyl.order()==order_abc and standard_extended.order()==order_tuple
 x=S.symbols('x');cp=[S.factor(M.charpoly(x).as_expr()) for M in [a,d,tuple_matrices[-2],tuple_matrices[-1]]]
 assert cp[0]==S.cyclotomic_poly(20,x)
 assert S.expand(cp[1]-(x-1)**2*S.cyclotomic_poly(3,x)*S.cyclotomic_poly(12,x))==0
 assert S.expand(cp[2]-(x*x-1)**4)==0
