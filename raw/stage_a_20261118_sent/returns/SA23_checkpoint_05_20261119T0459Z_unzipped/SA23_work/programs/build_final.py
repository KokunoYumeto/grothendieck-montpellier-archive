#!/usr/bin/env python3
"""Build the completed assessed dossier; save each program's complete output.

No source verdict or mathematical decision is generated by this orchestration.
Run only after all owner records are complete and frozen.
"""
import datetime,json,subprocess,sys
from pathlib import Path
P=Path(__file__).resolve().parent
W=P.parent
steps=[
 ('make_consolidation_plan.py','plan_build_output.json'),
 ('build_final_bibliography.py','bibliography_build_output.json'),
 ('finalize_dossier.py','finalize_output.json'),
 ('build_fate_coverage.py','fate_build_output.json'),
 ('validate_final.py','validation_run_output.json'),
]
rows=[]
for script,output in steps:
 r=subprocess.run([sys.executable,str(P/script)],cwd=W.parent,text=True,capture_output=True)
 (W/'outputs'/output).write_text(r.stdout)
 if r.stderr:(W/'outputs'/(output+'.stderr')).write_text(r.stderr)
 row=dict(program='programs/'+script,returncode=r.returncode,output='outputs/'+output,utc=datetime.datetime.now(datetime.timezone.utc).isoformat())
 rows.append(row)
 print(json.dumps(row),flush=True)
 if r.returncode:
  print(r.stderr)
  break
(W/'outputs/final_build_run.json').write_text(json.dumps(rows,indent=2)+'\n')
raise SystemExit(rows[-1]['returncode'])
