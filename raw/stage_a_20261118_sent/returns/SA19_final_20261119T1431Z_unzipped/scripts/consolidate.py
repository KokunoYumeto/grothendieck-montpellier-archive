# Balanced-brace BibTeX reader, preserving arbitrary mathematical braces.
def bib_entries(text):
    pos=0
    while True:
        m=re.search(r'@(\w+)\s*\{\s*([^,]+),',text[pos:])
        if not m:break
        start=pos+m.start();brace=pos+m.end()-1;depth=1;i=brace+1
        while i<len(text) and depth:
            if text[i]=='{' and (i==0 or text[i-1]!='\\'):depth+=1
            if text[i]=='}' and (i==0 or text[i-1]!='\\'):depth-=1
            i+=1
        yield m.group(2).strip(),text[start:i]
        pos=i
def field(block,name):
    m=re.search(r'\b'+re.escape(name)+r'\s*=\s*\{',block,re.I)
    if not m:return ''
    i=m.end();j=i;dep=1
    while j<len(block) and dep:
        if block[j]=='{' and block[j-1]!='\\':dep+=1
        if block[j]=='}' and block[j-1]!='\\':dep-=1
        j+=1
    return block[i:j-1]
