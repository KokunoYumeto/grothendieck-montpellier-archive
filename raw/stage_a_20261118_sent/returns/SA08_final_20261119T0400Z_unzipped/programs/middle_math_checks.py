# Sparse super-polynomials in two even and two odd variables. This computes,
# rather than merely labels, the mixed-coordinate obstruction.
def mul_super(A,B,pd=False):
 C={}
 for (a,b,J),u in A.items():
  for (c,d,K),v in B.items():
   if set(J)&set(K):continue
   sign=(-1)**sum(j>k for j in J for k in K)
   factor=comb(a+c,a)*comb(b+d,b) if pd else 1
   term=(a+c,b+d,tuple(sorted(J+K)));C[term]=C.get(term,0)+u*v*sign*factor
 return {k:v for k,v in C.items() if v}
def add_super(A,B,sign=1):
 C=A.copy()
 for k,v in B.items():C[k]=C.get(k,0)+sign*v
 return {k:v for k,v in C.items() if v}
