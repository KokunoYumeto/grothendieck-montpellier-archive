# Euler matrix check in rank2, all degrees through total weight5.
def basis(n,r):
 return [(a,b,J) for a in range(n+1) for b in range(n+1-a) for J in combinations(range(2),r) if a+b+r==n]
def d_term(v,pd=False):
 a,b,J=v;ans={}
 for j,e in enumerate((a,b)):
  if e and j not in J:
   ex=[a,b];ex[j]-=1;sgn=(-1)**sum(t<j for t in J);new=(ex[0],ex[1],tuple(sorted(J+(j,))))
   ans[new]=sgn*(1 if pd else e)
 return ans
def delta_term(v,pd=False):
 a,b,J=v;ans={}
 for pos,j in enumerate(J):
  ex=[a,b];ex[j]+=1;new=(ex[0],ex[1],J[:pos]+J[pos+1:]);ans[new]=(-1)**pos*(ex[j] if pd else 1)
 return ans
def mat(n,r,fn,pd=False):
 src=basis(n,r);dst=basis(n,r+1 if fn=='d' else r-1);B={v:i for i,v in enumerate(dst)}
 M=s.zeros(len(dst),len(src))
 for col,v in enumerate(src):
  for w,c in (d_term(v,pd) if fn=='d' else delta_term(v,pd)).items():M[B[w],col]=c
 return M
