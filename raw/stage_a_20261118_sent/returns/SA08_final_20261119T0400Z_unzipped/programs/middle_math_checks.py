# Direct polynomial integration, rather than substituting the beta formula.
def simplex_integral(indices):
 n=len(indices);x=s.symbols('x:'+str(n));expr=s.prod(x[j]**indices[j] for j in range(n))
 for j in reversed(range(n)):expr=s.integrate(expr,(x[j],0,1-sum(x[:j])))
 return s.factor(expr)
