@lru_cache(None)
def rec(inds,with_factor=True):
 if not inds:return 1
 n=len(inds);tot=inds[-1]+1;answer=0
 for ell in product(range(tot+1),repeat=n-1):
  if sum(ell)>tot:continue
  lam=tot-sum(ell)
  a=(-1)**sum(ell)*s.prod(comb(inds[j]+ell[j],ell[j]) for j in range(n-1))
  if with_factor:a*=comb(lam+n-1+sum(inds[:-1])+sum(ell),lam)
  answer+=a*rec(tuple(inds[j]+ell[j] for j in range(n-1)),with_factor)
 return int(answer)
