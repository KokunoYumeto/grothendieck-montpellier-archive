a,b=claims['CL-SA09-138M-027'],claims['CL-SA09-138L-011']
a['items']=unique([canon(x) for x in a['items']+b['items']]);a['scans']=sorted(set(a['scans']+b['scans']));a['lines']=unique(a['lines']+b['lines'])
a['his_statement']+=' | Later explicit formula: '+b['his_statement']
a['statement']='Let k be an algebraic closure of a characteristic-zero field k0, and let a finite reduced divisor on P1 over k0 have at least two geometric points. For its geometrically connected complement, the arithmetic étale fundamental-group extension induces Gal(k/k0)→Out(π1geom). At each k0-rational puncture, local tame inertia injects as Zhat(1), and the action on every such group is the same cyclotomic character. The canonical construction is outer; based automorphisms and literal peripheral tuples require choices.'
a['status_on_pages']='stated without proof: arithmetic extension and multiplier displayed on83; the Tate limit and independence of puncture index are explicit on94–95. No faithfulness assertion is made.'
a['computation']+='; later occurrence checked by the local Kummer description in workers/cote138_late/proofs.md.'
a['refs']=unique([canon(x) for x in a['refs']+b['refs']]);a['fate']+=' The later puncture-independence formulation is matched to SGA1 XIII and Oesterlé §2.5 in the late worker’s search record.'
del claims['CL-SA09-138L-011']

for row in entries:
 old=row['item_id'];row['item_id']=canon(old)
 if old in ITEM_ALIAS:
  old_verdict=row['verdict'];row['verdict']='merged'
  why=next(d['reason'] for d in decisions if d['from_id']==old)
  row['reason']=f'Cross-package merge into {row["item_id"]}. {why} Original component verdict: {old_verdict}. '+row['reason']
 # The target is already a separate field. Canonicalize only the spelling of
 # existing merged verdicts; no mathematical verdict is inferred here.
 if row['verdict'].startswith('merged') and row['verdict']!='merged':
  row['reason']='Component wording: '+row['verdict']+'. '+row['reason']
  row['verdict']='merged'

items=walk(sorted(items.values(),key=lambda x:int(x['id'].split('-')[-1])))
claims=walk(list(claims.values()));problems=walk(sorted(problems,key=lambda x:int(x['id'].split('-')[-1])))
for c in claims:c['items']=unique(c['items']);c['refs']=unique(c['refs'])
index=readtsv(ROOT.parent/'source/SA09_notes/NOTES_INDEX.tsv')
order={x['entry_id']:i for i,x in enumerate(index)}
entries=sorted(walk(entries),key=lambda x:order[x['entry_id']])
writejson('SA09_items.json',items);writejson('SA09_claims.json',claims);writejson('SA09_problems.json',problems)
writetsv('SA09_entries.tsv',['entry_id','item_id','verdict','reason'],entries)
writetsv('SA09_id_aliases.tsv',['from_id','to_id','reason'],decisions+[dict(from_id=a,to_id=b,reason='Bibliographic alias for the same opened work; component keys remain in their provenance files.') for a,b in REF_ALIAS.items()])

readings=[];links=[];project_leads=[];events=[]
for worker in WORKERS:
 d=ROOT/'workers'/worker
 readings.extend(readtsv(d/'readings.tsv'))
 for name in ['links.tsv','verified_project_links.tsv','additional_folder_links.tsv']:
  f=d/name
  if f.exists():links.extend(readtsv(f))
 f=d/'project_leads.tsv'
 if f.exists():project_leads.extend(readtsv(f))
 f=d/'CHECK_EVENTS.tsv'
 if not f.exists():raise RuntimeError('Worker events not ready: '+worker)
 worker_event_files=[f]+sorted(d.glob('qa_*_events.tsv'))
 for r in [r for ef in worker_event_files for r in readtsv(ef)]:
  events.append({'statement id':r.get('statement id',r.get('statement_id')),'date':r['date'],
   'who(model,effort,run)':r.get('who(model,effort,run)',r.get('who')),'type':r['type'],'outcome':r['outcome']})

# The explicit lead lists, not keyword verdicts, are maintained by the readers.
# Original middle/cote137 links with inaccessible endpoints are moved by a
# manually enumerated source-record selector in project_link_decisions.json.
decision_file=ROOT/'project_link_decisions.json'
if decision_file.exists():
 decisions_link=readjson(decision_file)
 for rule in decisions_link:
  if rule['action']=='move_to_reported_leads':
   matches=[l for l in links if l['from']==rule['from'] and l['to']==rule['to']]
   if len(matches)!=1:raise ValueError('Unmatched manual project-link decision '+str(rule))
   l=matches[0];links.remove(l)
   if 'current_evidence' in rule:l['evidence']=rule['current_evidence']
   project_leads.append(l)

for extra in ['root_verified_links.tsv']:
 f=ROOT/extra
 if f.exists():links.extend(readtsv(f))
for extra in ['root_check_events.tsv']:
 f=ROOT/extra
 if f.exists():events.extend(readtsv(f))

writetsv('SA09_readings.tsv',['cote','scan','line','reading','alternative','evidence','weight','confidence'],walk(readings))
writetsv('SA09_links.tsv',['kind','from','to','what','evidence','note_ids'],walk(links))
writetsv('SA09_project_links.tsv',['kind','from','to','what','evidence','note_ids'],walk([r for r in links if r['kind']=='our projects']))
writetsv('SA09_project_leads.tsv',['kind','from','to','what','evidence','note_ids'],walk(project_leads))
for d in decisions:
 events.append({'statement id':d['to_id'],'date':'2026-11-19','who(model,effort,run)':'GPT-6 Astra Pro; effort inherited/not exposed; SA09/root',
 'type':'used and rechecked in this run','outcome':'Cross-package identity review: '+d['reason']+' Retired component identifier '+d['from_id']+' remains an alias, not a second claim.'})
writetsv('CHECK_EVENTS.tsv',['statement id','date','who(model,effort,run)','type','outcome'],walk(events))

bib={};bib_sources={}
for worker in WORKERS:
 d=ROOT/'workers'/worker
 for chunk in re.split(r'(?m)(?=^@)','\n'.join(f.read_text() for f in [d/'references.bib']+sorted(d.glob('references_addendum.bib')))):
  m=re.match(r'@(\w+)\{([^,]+),',chunk)
  if not m:continue
  key=canon(m.group(2));chunk=chunk.replace('{'+m.group(2)+',','{'+key+',',1)
  bib_sources.setdefault(key,[]).append(worker)
  # Root copies have the extra checked chronology; all source-specific reading
  # scopes survive in each worker bibliography and CHECK_EVENTS.
  if key not in bib or worker=='cote138_middle':bib[key]=chunk.strip()
extra=ROOT/'root_project_references.bib'
if extra.exists():
 for chunk in re.split(r'(?m)(?=^@)',extra.read_text()):
  m=re.match(r'@\w+\{([^,]+),',chunk)
  if m:bib[m.group(1)]=chunk.strip()
(ROOT/'SA09_references.bib').write_text('% Every verification scope is qualified in CHECK_EVENTS.tsv and the component records.\n\n'+'\n\n'.join(bib[k] for k in sorted(bib))+'\n')
writejson('reference_provenance.json',bib_sources)

