for worker in WORKERS:
 d=ROOT/'workers'/worker
 if worker=='cote137':
  rows=readtsv(d/'search_log.tsv')
  for c in readjson(d/'claims.json'):
   records=[r['search_id'] for r in rows if c['id'] in r['claim_ids']]
   if not records:raise ValueError('No recorded search: '+c['id'])
   coverage.append(dict(claim_id=canon(c['id']),worker=worker,search_records=';'.join(records),record_file=f'workers/{worker}/search_log.tsv'))
 elif worker=='cote138_early':
  for r in readtsv(d/'search_log.tsv'):coverage.append(dict(claim_id=canon(r['claim_id']),worker=worker,search_records=r['claim_id'],record_file=f'workers/{worker}/search_log.tsv'))
 elif worker=='cote138_middle':
  for r in readtsv(d/'claim_search.tsv'):coverage.append(dict(claim_id=canon(r['claim_id']),worker=worker,search_records=r['search_ids'],record_file=f'workers/{worker}/search_log.json'))
 else:
  for k,v in readjson(d/'claim_search_groups.json').items():coverage.append(dict(claim_id=canon(k),worker=worker,search_records=';'.join(v) if isinstance(v,list) else v,record_file=f'workers/{worker}/search_log.tsv'))
writetsv('SA09_claim_search_coverage.tsv',['claim_id','worker','search_records','record_file'],coverage)

counts=dict(entries=len(entries),items=len(items),claims=len(claims),problems=len(problems),readings=len(readings),links=len(links),reported_project_leads=len(project_leads),references=len(bib),check_events=len(events),verdicts=dict(Counter(r['verdict'] for r in entries)),item_kinds=dict(Counter(r['kind'] for r in items)),claim_classes=dict(Counter(r['class'] for r in claims)),component_claim_count=sum(len(readjson(ROOT/'workers'/w/'claims.json')) for w in WORKERS),retired_item_ids=ITEM_ALIAS,retired_claim_ids=CLAIM_ALIAS)
status_file=ROOT/'claim_status_groups.tsv'
if status_file.exists():
 status_rows=readtsv(status_file)
 if Counter(r['claim_id'] for r in status_rows)!=Counter(c['id'] for c in claims):raise ValueError('Status grouping does not exactly cover canonical claims')
 counts['claim_status_groups']=dict(Counter(r['status_group'] for r in status_rows))
 counts['claim_statuses_verbatim']=dict(Counter(c['status_on_pages'] for c in claims))
direction_file=ROOT/'SA09_directions.md'
if direction_file.exists():counts['directions']=len(re.findall(r'^## D\d+\.',direction_file.read_text(),re.M))
writejson('counts.json',counts)
print(json.dumps(counts,ensure_ascii=False,indent=2))
