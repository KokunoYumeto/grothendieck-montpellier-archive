#!/usr/bin/env python3
"""Assemble the independently read ledgers using explicit human merge decisions.

This program never assigns a source verdict from headings or textual cues.
The six item aliases and one claim alias below were decided after reading both
source passages. Component files remain unchanged as provenance records.
"""
import csv,json,re
from collections import Counter
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
WORKERS=['cote137','cote138_early','cote138_middle','cote138_late']
ITEM_ALIAS={'SA09-234':'SA09-129','SA09-266':'SA09-239',
 'SA09-248':'SA09-110','SA09-249':'SA09-110','SA09-295':'SA09-110','SA09-253':'SA09-155'}
CLAIM_ALIAS={'CL-SA09-138L-011':'CL-SA09-138M-027'}
REF_ALIAS={'M-SGA1':'SGA1','M-Belyi1980':'Belyi1980','M-Grothendieck1984':'Esquisse1984',
 'M-Guillot2014':'GuillotDessins','M-Collas2026':'Collas2026'}
ALIASES={**ITEM_ALIAS,**CLAIM_ALIAS,**REF_ALIAS}

def canon(s): return ALIASES.get(s,s)
def tx(s):
 if not isinstance(s,str):return s
 for a,b in sorted(ALIASES.items(),key=lambda x:-len(x[0])):
  s=re.sub(r'(?<![A-Za-z0-9_])'+re.escape(a)+r'(?![A-Za-z0-9_])',b,s)
 return s
def walk(x):
 if isinstance(x,str):return tx(x)
 if isinstance(x,list):return [walk(v) for v in x]
 if isinstance(x,dict):return {k:walk(v) for k,v in x.items()}
 return x
def array(v):return v if isinstance(v,list) else [v]
def unique(xs):return list(dict.fromkeys(xs))
def readjson(p):return json.loads(p.read_text())
def readtsv(p):return list(csv.DictReader(p.open(),delimiter='\t'))
def writejson(name,data):(ROOT/name).write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
def writetsv(name,fields,rows):
 with (ROOT/name).open('w') as f:
  w=csv.DictWriter(f,fieldnames=fields,delimiter='\t',extrasaction='ignore');w.writeheader();w.writerows(rows)

items={};claims={};problems=[];entries=[]
for worker in WORKERS:
 d=ROOT/'workers'/worker
 for item in readjson(d/'items.json'):
  if item['id'] in items:raise ValueError('Duplicate item '+item['id'])
  item['cote']=str(item['cote']);item['lines']=array(item['lines']);items[item['id']]=item
 for claim in readjson(d/'claims.json'):
  if claim['id'] in claims:raise ValueError('Duplicate claim '+claim['id'])
  claim['cote']=str(claim['cote']);claim['lines']=array(claim['lines']);claims[claim['id']]=claim
 problems.extend(readjson(d/'problems.json'));entries.extend(readtsv(d/'entries.tsv'))

decisions=[
 dict(from_id='SA09-234',to_id='SA09-129',reason='Same explicit degree-six S3 quotient and special fibres. Scan19 writes the equation; scan78 supplies a matching unlabelled diagram. Identifying the latter arrow with the former function remains an attributed interpretation, not an ink reading.'),
 dict(from_id='SA09-266',to_id='SA09-239',reason='Same arithmetic outer action and common cyclotomic inertia character, revisited at rational punctures with an explicit Tate-module formula and independence of puncture index.'),
 dict(from_id='SA09-248',to_id='SA09-110',reason='The bounded textual comparison asks which universal Belyi and arithmetic-faithfulness assertions are actually present; the packet-by-packet absence findings form one scope item.'),
 dict(from_id='SA09-249',to_id='SA09-110',reason='Repeated absence of the universal converse in a second packet; merged with the whole-cote quantifier audit.'),
 dict(from_id='SA09-295',to_id='SA09-110',reason='The late packet makes the same bounded converse/faithfulness comparison and adds the distinction between one finite class set and their entire union.'),
 dict(from_id='SA09-253',to_id='SA09-155',reason='Same reported CM-parity and full-group comparison lead across the Fermat and conic examples. Different geometric inputs and named research statuses remain explicitly distinguished.'),
 dict(from_id='CL-SA09-138L-011',to_id='CL-SA09-138M-027',reason='Same cyclotomic action on tame inertia; the later occurrence makes puncture independence explicit. At least two punctures is retained for the full local inertia inclusion on P1.'),
]
for old,new in ITEM_ALIAS.items():
 a,b=items[new],items[old]
 a['sources']=unique(a['sources']+b['sources']);a['scans']=sorted(set(a['scans']+b['scans']))
 a['lines']=unique(a['lines']+b['lines'])
 a['his_words']+=' | Later/source comparison: '+b['his_words']
 del items[old]

