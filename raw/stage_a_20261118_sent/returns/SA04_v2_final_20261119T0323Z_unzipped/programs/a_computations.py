# Normalized group cochains for C2 with trivial action on C_m.
def fval(value,args,mod):return value%mod if all(args) else 0
def dc(value,args,mod):
    degree=len(args)-1
    result=fval(value,args[1:],mod)
    for i in range(1,degree+1):
        merged=args[:i-1]+((args[i-1]+args[i])%2,)+args[i+1:]
        result+=(-1)**i*fval(value,merged,mod)
    result+=(-1)**(degree+1)*fval(value,args[:-1],mod)
    return result%mod
for mod in (2,4):
    cycles=[v for v in range(mod) if all(dc(v,t,mod)==0 for t in product((0,1),repeat=4))]
    images=set(tuple(dc(v,t,mod) for t in product((0,1),repeat=3)) for v in range(mod))
    assert images=={(0,)*8}
    report('C80/C83 normalized H3(C2;C'+str(mod)+')',{'cycle values at111':cycles,'all degree2 coboundaries zero':True})
# Universal reduced quadratic-module identities, integer variables then mod4.
