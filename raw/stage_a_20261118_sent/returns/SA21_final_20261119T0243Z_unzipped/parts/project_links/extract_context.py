"""Navigation only: extract supplied note context lines with stable note IDs.
No target-match verdicts are generated by this script.
"""
from pathlib import Path
import json,hashlib,datetime
P=Path(__file__).parent
B=Path('/workspace/scratch/4017236f14bf')
note=B/'sources/notes/pro/MPL_156-1+156-2_notes.md'
rows=[];i=0;heading=''
for n,line in enumerate(note.read_text().splitlines(),1):
    if line.startswith('### '):i+=1;heading=line[4:]
    if line.startswith('**Context:**'):
        rows.append({'note_id':f'MPL_156-1+156-2#{i}','line':n,'heading':heading,'context':line})
(P/'context_navigation.json').write_text(json.dumps(rows,ensure_ascii=False,indent=2)+'\n')
(P/'context_navigation.txt').write_text('\n\n'.join(f"{r['note_id']} source line{r['line']} — {r['heading']}\n{r['context']}" for r in rows)+'\n')
files=['README.md','notes/RESULTS_STATE.md','DOSSIER_STATEMENTS_WITH_STATUS.md','NEW_RESULTS.md']
manifest=[]
for name in files:
    file=B/'prior_context/extracted'/name;data=file.read_bytes()
    manifest.append({'relative_path':name,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest(),'lines':len(data.decode().splitlines())})
    out=P/(name.replace('/','__')+'.numbered.txt')
    out.write_text('\n'.join(f'{n:04d}: {s}' for n,s in enumerate(data.decode().splitlines(),1))+'\n')
(P/'source_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps({'context_paragraphs':len(rows),'headings':i,'source_hash':hashlib.sha256(note.read_bytes()).hexdigest(),'retrieved_context_package':'69, not the original package48','timestamp_utc':datetime.datetime.now(datetime.timezone.utc).isoformat()},indent=2))
