def col(e): v=[0]*(3*n); v[e[0]]=1; v[n+e[1]]=1; v[2*n+e[2]]=1; return v
# Smith normal form diagonal via integer elimination (small sizes)
def snf_diag(rows):
    A=[r[:] for r in rows]; m=len(A); k=len(A[0]); diag=[]
    r=0
    for c in range(k):
        # find pivot
        while True:
            piv=[(abs(A[i][j]),i,j) for i in range(r,m) for j in range(c,k) if A[i][j]!=0]
            if not piv: return diag
            _,i,j=min(piv)
            A[r],A[i]=A[i],A[r]
            for row in A: row[c],row[j]=row[j],row[c]
            p=A[r][c]; done=True
            for i in range(r+1,m):
                q=A[i][c]//p
                if q: A[i]=[a-q*b for a,b in zip(A[i],A[r])]
                if A[i][c]!=0: done=False
            for j in range(c+1,k):
                q=A[r][j]//p
                if q:
                    for row in A: row[j]-=q*row[c]
                if A[r][j]!=0: done=False
            if done:
                # ensure p divides all remaining
                bad=[(i,j) for i in range(r+1,m) for j in range(c+1,k) if A[i][j]%p]
                if bad:
                    i,j=bad[0]; A[r]=[a+b for a,b in zip(A[r],A[i])]; continue
                diag.append(abs(p)); r+=1; break
    return diag
# lattice generated by columns of S; order of chi=1 in Z^{3n}/L
cols=[col(e) for e in S]
# rows of matrix = generators as rows
D=snf_diag(cols)
print('SNF nonzero diagonal of support lattice (as row generators):',[x for x in D if x!=1][:10],'rank',len(D))
# order of 1: solve 1 = sum z_e col(e) rationally using basis; compute minimal d with d*1 in lattice via HNF approach
def lattice_basis(vecs,N):
    rows=[list(v) for v in vecs if any(v)]; basis=[]
    for c in range(N):
        piv=[r for r in rows if r[c]!=0]; others=[r for r in rows if r[c]==0]
        while len(piv)>1:
            piv.sort(key=lambda r:abs(r[c])); p=piv[0]; new=[p]
            for r in piv[1:]:
                q=r[c]//p[c]; r2=[a-q*b for a,b in zip(r,p)]
                if r2[c]!=0: new.append(r2)
                elif any(r2): others.append(r2)
            piv=new
        if piv: basis.append(piv[0])
        rows=others
    return basis
B=lattice_basis(cols,3*n)
t=[Fr(1)]*(3*n); z=[]
for b in B:
    c=next(i for i in range(3*n) if b[i]!=0); zk=t[c]/b[c]; z.append(zk); t=[ti-zk*bi for ti,bi in zip(t,b)]
assert not any(t), 'chi not in rational span'
from math import lcm
